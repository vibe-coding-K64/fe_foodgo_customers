/// Loai bo dau tieng Viet de phuc vu tim kiem khong phan biet dau.
///
/// Vi du: "trà" -> "tra", "trá" -> "tra", "TRÀ SỮA" -> "tra sua"
class VietnameseNormalizer {
  VietnameseNormalizer._();

  /// Map cac ky tu tieng Viet co dau thanh ky tu khong dau.
  static const Map<String, String> _diacriticsMap = {
    // Cac nguyen am co dau
    'à': 'a', 'á': 'a', 'ả': 'a', 'ã': 'a', 'ạ': 'a',
    'ă': 'a', 'ằ': 'a', 'ắ': 'a', 'ẳ': 'a', 'ẵ': 'a', 'ặ': 'a',
    'â': 'a', 'ầ': 'a', 'ấ': 'a', 'ẩ': 'a', 'ẫ': 'a', 'ậ': 'a',
    'è': 'e', 'é': 'e', 'ẻ': 'e', 'ẽ': 'e', 'ẹ': 'e',
    'ê': 'e', 'ề': 'e', 'ế': 'e', 'ể': 'e', 'ễ': 'e', 'ệ': 'e',
    'ì': 'i', 'í': 'i', 'ỉ': 'i', 'ĩ': 'i', 'ị': 'i',
    'ò': 'o', 'ó': 'o', 'ỏ': 'o', 'õ': 'o', 'ọ': 'o',
    'ô': 'o', 'ồ': 'o', 'ố': 'o', 'ổ': 'o', 'ỗ': 'o', 'ộ': 'o',
    'ơ': 'o', 'ờ': 'o', 'ớ': 'o', 'ở': 'o', 'ỡ': 'o', 'ợ': 'o',
    'ù': 'u', 'ú': 'u', 'ủ': 'u', 'ũ': 'u', 'ụ': 'u',
    'ư': 'u', 'ừ': 'u', 'ứ': 'u', 'ử': 'u', 'ữ': 'u', 'ự': 'u',
    'ỳ': 'y', 'ý': 'y', 'ỷ': 'y', 'ỹ': 'y', 'ỵ': 'y',
    // Ky tu hoa
    'À': 'A', 'Á': 'A', 'Ả': 'A', 'Ã': 'A', 'Ạ': 'A',
    'Ă': 'A', 'Ằ': 'A', 'Ắ': 'A', 'Ẳ': 'A', 'Ẵ': 'A', 'Ặ': 'A',
    'Â': 'A', 'Ầ': 'A', 'Ấ': 'A', 'Ẩ': 'A', 'Ẫ': 'A', 'Ậ': 'A',
    'È': 'E', 'É': 'E', 'Ẻ': 'E', 'Ẽ': 'E', 'Ẹ': 'E',
    'Ê': 'E', 'Ề': 'E', 'Ế': 'E', 'Ể': 'E', 'Ễ': 'E', 'Ệ': 'E',
    'Ì': 'I', 'Í': 'I', 'Ỉ': 'I', 'Ĩ': 'I', 'Ị': 'I',
    'Ò': 'O', 'Ó': 'O', 'Ỏ': 'O', 'Õ': 'O', 'Ọ': 'O',
    'Ô': 'O', 'Ồ': 'O', 'Ố': 'O', 'Ổ': 'O', 'Ỗ': 'O', 'Ộ': 'O',
    'Ơ': 'O', 'Ờ': 'O', 'Ớ': 'O', 'Ở': 'O', 'Ỡ': 'O', 'Ợ': 'O',
    'Ù': 'U', 'Ú': 'U', 'Ủ': 'U', 'Ũ': 'U', 'Ụ': 'U',
    'Ư': 'U', 'Ừ': 'U', 'Ứ': 'U', 'Ử': 'U', 'Ữ': 'U', 'Ự': 'U',
    'Ỳ': 'Y', 'Ý': 'Y', 'Ỷ': 'Y', 'Ỹ': 'Y', 'Ỵ': 'Y',
  };

  /// Chuyen mot chuoi thanh chuoi khong dau tieng Viet.
  ///
  /// VD: "Trà sữa" -> "tra sua"
  ///     "Tôm Hùm" -> "tom hum"
  static String normalize(String text) {
    final buffer = StringBuffer();
    for (int i = 0; i < text.length; i++) {
      final char = text[i];
      buffer.write(_diacriticsMap[char] ?? char);
    }
    return buffer.toString();
  }

  /// Kiem tra xem [query] co xuat hien trong [text] hay khong,
  /// khong phan biet dau tieng Viet va khong phan biet hoa thuong.
  ///
  /// [query] duoc tu dong normalize (bo dau + chuyen thanh chu thuong).
  /// [text] duoc tu dong normalize (bo dau + chuyen thanh chu thuong).
  ///
  /// VD: matchesDiacritic("tra", "Trà sữa") = true
  ///     matchesDiacritic("tra sua", "Trà Sữa") = true
  ///     matchesDiacritic("ca", "Cá") = true
  ///     matchesDiacritic("pizza", "Trà sữa") = false
  static bool matchesDiacritic(String query, String text) {
    if (query.isEmpty) return true;
    final normalizedQuery = normalize(query.toLowerCase());
    final normalizedText = normalize(text.toLowerCase());
    return normalizedText.contains(normalizedQuery);
  }
}
